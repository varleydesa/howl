create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(private.current_role() = 'admin'::public.app_role, false)
$$;

create or replace function private.can_access_startup(target_startup_id text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    private.is_admin()
    or exists (
      select 1
      from public.profile_startups ps
      where ps.profile_id = private.current_profile_id()
        and ps.startup_id = target_startup_id
    )
$$;

create or replace function private.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  normalized_email text := lower(coalesce(new.email, ''));
  display_name text := coalesce(
    nullif(new.raw_user_meta_data ->> 'name', ''),
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    split_part(normalized_email, '@', 1)
  );
begin
  update public.profiles
  set auth_user_id = new.id,
      name = case when name = '' then display_name else name end
  where email = normalized_email;

  if not found then
    insert into public.profiles (id, auth_user_id, name, email, role, organization)
    values (
      new.id::text,
      new.id,
      display_name,
      normalized_email,
      'empreendedor',
      ''
    );
  end if;

  return new;
end;
$$;

