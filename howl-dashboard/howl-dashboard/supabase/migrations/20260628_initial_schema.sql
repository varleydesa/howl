insert into public.entrepreneur_answers
  (cycle_id, question_id, score, comment, status)
select
  c.id,
  q.id,
  greatest(
    0,
    least(
      5,
      round(
        t.target
        + ((((q.position - 1) % 5) - 2) * 0.16)
        + case
            when t.startup_id = 'healthflow' then 0.82
            when t.startup_id = 'agrosense' then 0.32
            else 0.18
          end,
        1
      )
    )
  ),
  '',
  'enviada'
from seed_targets t
join public.assessment_periods p
  on p.year = 2026 and p.month = t.month
join public.assessment_cycles c
  on c.startup_id = t.startup_id and c.period_id = p.id
join public.questions q
  on q.journey_id = t.journey_id
on conflict (cycle_id, question_id) do nothing;

insert into public.evaluator_answers
  (cycle_id, question_id, score, comment, status)
select
  c.id,
  q.id,
  greatest(
    0,
    least(
      5,
      round(
        t.target
        - ((((q.position - 1) % 5) - 2) * 0.16)
        + case when t.startup_id = 'healthflow' then -0.42 else -0.08 end,
        1
      )
    )
  ),
  case
    when t.target < 3
      then 'Necessário transformar hipótese em evidência mensurável.'
    else 'Boa base, com oportunidade de documentar aprendizados.'
  end,
  'enviada'
from seed_targets t
join public.assessment_periods p
  on p.year = 2026 and p.month = t.month
join public.assessment_cycles c
  on c.startup_id = t.startup_id and c.period_id = p.id
join public.questions q
  on q.journey_id = t.journey_id
on conflict (cycle_id, question_id) do nothing;

create or replace view public.assessment_question_results
with (security_invoker = true)
as
select
  c.id as cycle_id,
  c.startup_id,
  p.id as period_id,
  p.month,
  p.year,
  p.label,
  j.id as journey_id,
  j.position as journey_position,
  j.name as journey_name,
  j.gate,
  q.id as question_id,
  q.position as question_position,
  q.prompt,
  ea.score as entrepreneur_score,
  ea.comment as entrepreneur_comment,
  ea.status as entrepreneur_status,
  ea.updated_at as entrepreneur_updated_at,
  va.score as evaluator_score,
  va.comment as evaluator_comment,
  va.status as evaluator_status,
  va.updated_at as evaluator_updated_at,
  case
    when ea.score is not null and va.score is not null
      then round((ea.score * 0.4) + (va.score * 0.6), 2)
    else null
  end as final_score,
  case
    when ea.score is not null and va.score is not null
      then round(ea.score - va.score, 2)
    else null
  end as gap
from public.assessment_cycles c
join public.assessment_periods p on p.id = c.period_id
join public.questions q on q.active
join public.journeys j on j.id = q.journey_id
left join public.entrepreneur_answers ea
  on ea.cycle_id = c.id and ea.question_id = q.id
left join public.evaluator_answers va
  on va.cycle_id = c.id and va.question_id = q.id;

revoke all on public.assessment_question_results from anon;
grant select on public.assessment_question_results to authenticated;

commit;
